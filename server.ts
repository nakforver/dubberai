function escapeFFmpegFilterPath(value: string): string {
  return value
    .replace(/\\/g, '/')
    .replace(/'/g, "\\'")
    .replace(/:/g, '\\:');
}

const KHMER_COMBINING_REGEX = /[\u17B4-\u17D3\u17DD]/;

function formatKhmerSubtitleText(text: string): string {
  if (!text) return '';
  const normalized = text.normalize('NFC');
  if (!/[\u1780-\u17FF]/.test(normalized)) return normalized;
  try {
    const clean = normalized.replace(/\u200B+/g, '');
    const segmenter = new Intl.Segmenter('km', { granularity: 'word' });
    const segments = [...segmenter.segment(clean)].map(s => s.segment);
    let result = '';
    for (let i = 0; i < segments.length; i++) {
      const seg = segments[i];
      result += seg;
      const next = segments[i + 1];
      if (
        next &&
        !/\s/.test(seg) &&
        !/\s/.test(next) &&
        !seg.endsWith('\u17D2') &&
        !KHMER_COMBINING_REGEX.test(next[0])
      ) {
        result += '\u200B';
      }
    }
    return result;
  } catch (e) {
    return normalized;
  }
}

function srtTimeToAssTime(srtTime: string): string {
  const clean = (srtTime || '').trim().replace(',', '.');
  const parts = clean.split(':');
  let h = 0, m = 0, s = 0;
  if (parts.length === 3) {
    h = parseInt(parts[0], 10) || 0;
    m = parseInt(parts[1], 10) || 0;
    s = parseFloat(parts[2]) || 0;
  } else if (parts.length === 2) {
    m = parseInt(parts[0], 10) || 0;
    s = parseFloat(parts[1]) || 0;
  } else {
    s = parseFloat(parts[0]) || 0;
  }
  const totalCs = Math.max(0, Math.round(s * 100));
  const secs = Math.floor(totalCs / 100);
  const cs = totalCs % 100;
  const mTotal = m + Math.floor(secs / 60);
  const finalSecs = secs % 60;
  const hTotal = h + Math.floor(mTotal / 60);
  const finalMins = mTotal % 60;
  return `${hTotal}:${String(finalMins).padStart(2, '0')}:${String(finalSecs).padStart(2, '0')}.${String(cs).padStart(2, '0')}`;
}

function convertSrtToAss(srtContent: string, width = 1280, height = 720): string {
  const isPortrait = height > width;
  const playResX = width || (isPortrait ? 720 : 1280);
  const playResY = height || (isPortrait ? 1280 : 720);
  const fontSize = isPortrait ? 44 : 38;
  const marginV = isPortrait ? 70 : 42;
  const marginLR = isPortrait ? 35 : 45;
  const outline = isPortrait ? 2.8 : 2.6;
  const shadow = isPortrait ? 1.2 : 1.0;

  const header = `[Script Info]
; Script generated by DubberAI
ScriptType: v4.00+
PlayResX: ${playResX}
PlayResY: ${playResY}
ScaledBorderAndShadow: yes
YCbCr Matrix: None

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Default,Noto Sans Khmer,${fontSize},&H00FFFFFF,&H000000FF,&H00000000,&H80000000,1,0,0,0,100,100,0,0,1,${outline},${shadow},2,${marginLR},${marginLR},${marginV},1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
`;

  const clean = srtContent.replace(/^\uFEFF/, '').replace(/\r\n/g, '\n').replace(/\r/g, '\n');
  const blocks = clean.split(/\n\s*\n/);
  const events: string[] = [];

  for (const block of blocks) {
    const lines = block.trim().split('\n').map(l => l.trim()).filter(Boolean);
    if (lines.length === 0) continue;

    let timeIndex = -1;
    for (let i = 0; i < lines.length; i++) {
      if (lines[i].includes('-->')) {
        timeIndex = i;
        break;
      }
    }
    if (timeIndex === -1) continue;

    const [rawStart, rawEnd] = lines[timeIndex].split(/\s*-->\s*/);
    const startAss = srtTimeToAssTime(rawStart);
    const endAss = srtTimeToAssTime(rawEnd);

    const textLines = lines.slice(timeIndex + 1);
    if (textLines.length === 0) continue;

    const formattedText = textLines
      .map(line => formatKhmerSubtitleText(line).replace(/\{/g, '\\{').replace(/\}/g, '\\}'))
      .join('\\N');

    events.push(`Dialogue: 0,${startAss},${endAss},Default,,0,0,0,,${formattedText}`);
  }

  return header + events.join('\n') + '\n';
}

