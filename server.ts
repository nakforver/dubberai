function parseTimestamp(value: string | number | undefined): number | null {
  if (typeof value === 'number') {
    return Number.isFinite(value) && value >= 0 ? value : null;
  }
  if (!value || typeof value !== 'string') return null;
  const parts = value.replace(',', '.').trim().split(':').map((part) => Number(part));
  if (parts.some((part) => !Number.isFinite(part))) return null;
  if (parts.length === 3) return parts[0] * 3600 + parts[1] * 60 + parts[2];
  if (parts.length === 2) return parts[0] * 60 + parts[1];
  if (parts.length === 1) return parts[0];
  return null;
}

function formatSeconds(seconds: number): string {
  return seconds.toFixed(3);
}

function formatTimelineTimestamp(seconds: number): string {
  const rounded = Math.max(0, Math.round(seconds * 1000) / 1000);
  const hours = Math.floor(rounded / 3600);
  const minutes = Math.floor((rounded % 3600) / 60);
  const remaining = rounded % 60;
  return hours > 0
    ? `${hours}:${String(minutes).padStart(2, '0')}:${remaining.toFixed(3).padStart(6, '0')}`
    : `${minutes}:${remaining.toFixed(3).padStart(6, '0')}`;
}

function normalizeSubtitleTimeline(lines: any[]): any[] {
  return lines
    .map((line, index) => {
      const start = parseTimestamp(String(line?.start ?? ''));
      let end = parseTimestamp(String(line?.end ?? ''));
      if (start === null || start < 0) {
        console.warn(`[TIMELINE] Dropping subtitle ${index + 1}: invalid start timestamp`);
        return null;
      }
      if (end === null || end <= start || end - start < 0.2) {
        const nextStart = parseTimestamp(String(lines[index + 1]?.start ?? ''));
        end = nextStart !== null && nextStart > start ? nextStart : start + 0.75;
        console.warn(
          `[TIMELINE] Normalized subtitle ${index + 1} end to ${formatTimelineTimestamp(end)}`
        );
      }
      return {
        ...line,
        start: formatTimelineTimestamp(start),
        end: formatTimelineTimestamp(end)
      };
    })
    .filter(Boolean);
}

function buildAtempoFilter(rate: number): string {
  if (rate <= 1) return '';
  const filters: string[] = [];
  let remaining = rate;
  while (remaining > 2) {
    filters.push('atempo=2.0000');
    remaining /= 2;
  }
  if (remaining > 1.0001) {
    filters.push(`atempo=${remaining.toFixed(4)}`);
  }
  return filters.join(',');
}

function validateSubtitleLine(value: any, index: number): SubtitleLine {
  if (!value || typeof value !== 'object') {
    throw new Error(`Invalid subtitle entry at index ${index}`);
  }
  const id = typeof value.id === 'string' || typeof value.id === 'number'
    ? String(value.id)
    : '';
  if (!id) {
    throw new Error(`Invalid subtitle ID at index ${index}`);
  }
  if (typeof value.text !== 'string' || value.text.trim().length === 0) {
    throw new Error(`Invalid subtitle text at index ${index}`);
  }
  const startSeconds = parseTimestamp(value.start);
  const endSeconds = parseTimestamp(value.end);
  if (startSeconds === null || startSeconds < 0) {
    throw new Error(`Invalid start timestamp at subtitle index ${index}`);
  }
  if (endSeconds === null || endSeconds <= startSeconds) {
    throw new Error(
      `Invalid end timestamp at subtitle index ${index}: ` +
      `start=${String(value.start)} end=${String(value.end)}`
    );
  }
  const rawGender = typeof value.gender === 'string' ? value.gender.toLowerCase().trim() : '';
  let gender: 'female' | 'male' | undefined = undefined;
  if (rawGender.includes('female') || rawGender.includes('woman') || rawGender.includes('girl') || rawGender.includes('ស្រី')) {
    gender = 'female';
  } else if (rawGender.includes('male') || rawGender.includes('man') || rawGender.includes('boy') || rawGender.includes('ប្រុស')) {
    gender = 'male';
  }

  const rawSpeaker = typeof value.speaker === 'string' ? value.speaker.trim() : (typeof value.speakerId === 'string' ? value.speakerId.trim() : '');
  const rawSpeakerName = typeof value.speakerName === 'string' ? value.speakerName.trim() : '';
  const speaker = rawSpeaker || (gender === 'female' ? 'speaker_001' : 'speaker_002');
  const speakerName = rawSpeakerName || (gender === 'female' ? 'Speaker 1 (ស្រី)' : 'Speaker 2 (ប្រុស)');

  return {
    id,
    start: String(value.start),
    end: String(value.end),
    text: value.text.trim(),
    ...(gender ? { gender } : {}),
    speaker,
    speakerName
  };
}

function validateExportAudioMetadata(value: any): AudioSegmentMetadata[] {
  if (!Array.isArray(value)) {
    throw new Error('Export audio metadata must be a JSON array');
  }
  const keys = new Set<string>();
  return value.map((item: any, index: number) => {
    if (!item || typeof item !== 'object') {
      throw new Error(`Invalid export audio metadata entry at index ${index}`);
    }
    if (typeof item.key !== 'string' || !/^audio_\d+$/.test(item.key)) {
      throw new Error(`Invalid audio metadata key at index ${index}`);
    }
    if (keys.has(item.key)) {
      throw new Error(`Duplicate audio metadata key: ${item.key}`);
    }
    keys.add(item.key);

    const startSeconds = parseTimestamp(item.start);
    const endSeconds = parseTimestamp(item.end);
    if (startSeconds === null || startSeconds < 0) {
      throw new Error(`Invalid start timestamp for ${item.key}`);
    }
    if (endSeconds === null || endSeconds <= startSeconds) {
      throw new Error(`Invalid end timestamp for ${item.key}`);
    }
    if (item.segmentId !== undefined && (typeof item.segmentId !== 'string' || !item.segmentId)) {
      throw new Error(`Invalid segment ID for ${item.key}`);
    }
    if (
      item.expectedDuration !== undefined &&
      (!Number.isFinite(Number(item.expectedDuration)) || Number(item.expectedDuration) <= 0)
    ) {
      throw new Error(`Invalid expected TTS duration for ${item.key}`);
    }

    return {
      ...item,
      start: String(item.start),
      end: String(item.end)
    };
  });
}

